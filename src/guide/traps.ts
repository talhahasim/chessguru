/**
 * Data for the PDF guide (scripts/build-guide.ts). Traps that also have a video come from the lessons
 * (see VIDEO_TRAPS); these are guide-only traps. Every line is checked by `npx tsx scripts/check-guide.ts`.
 *
 * Plies are 1-based positions in `line` (ply 1 = the first move of the line).
 */
export type Level = "400–600" | "600–800" | "800–1000";

export type GuideStep = { plies: number; text: string };

export type GuideTrap = {
  id: string;
  name: string;
  opening: string;
  level: Level;
  /** The side that sets the trap (diagrams of the trap are shown from this side). */
  hero: Color;
  startFen?: string;
  hook: string;
  line: string[];
  /** Explanation of the line in chunks; the plies add up to line.length. */
  steps: GuideStep[];
  /** The winning move (green arrow in the trap diagram). */
  keyPly: number;
  /** The victim's mistake that allows it. */
  mistakePly: number;
  result: string;
  remember: string[];
  defense: {
    /** Plies of `line` played before the defender deviates (the wrong move is line[branchPly]). */
    branchPly: number;
    /** The correct defence from there (first move = the fix). */
    moves: string[];
    text: string;
    tips: string[];
  };
};

